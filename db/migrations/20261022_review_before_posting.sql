-- The signed-in creator's drafts, newest activity first.
-- p_contest_id: one campaign, or NULL for all.
-- p_status: all | pending_review | revision_requested | approved (not posted)
--           | posted | approved_all (approved, posted or not) | rejected | withdrawn
-- Returns { total, counts: { display_status: n }, rows: [...] }.
CREATE OR REPLACE FUNCTION public.my_content_drafts_page(
  p_contest_id uuid,
  p_status text,
  p_offset integer,
  p_limit integer
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid    uuid := auth.uid();
  v_status text := COALESCE(NULLIF(btrim(COALESCE(p_status, '')), ''), 'all');
  v_offset integer := GREATEST(COALESCE(p_offset, 0), 0);
  v_limit  integer := LEAST(GREATEST(COALESCE(p_limit, 30), 1), 100);
  v_counts jsonb;
  v_total  bigint;
  v_rows   jsonb;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('total', 0, 'counts', '{}'::jsonb, 'rows', '[]'::jsonb);
  END IF;

  WITH mine AS (
    SELECT d.*, public.content_draft_display_status(d) AS display_status
    FROM public.content_drafts d
    WHERE d.creator_id = v_uid
      AND (p_contest_id IS NULL OR d.contest_id = p_contest_id)
  ),
  counted AS (
    SELECT COALESCE(jsonb_object_agg(s.display_status, s.n), '{}'::jsonb) AS counts
    FROM (SELECT m.display_status, count(*) AS n FROM mine m GROUP BY m.display_status) s
  ),
  filtered AS (
    SELECT m.*
    FROM mine m
    WHERE v_status = 'all'
       OR (v_status = 'approved_all' AND m.status = 'approved')
       OR m.display_status = v_status
  )
  SELECT
    (SELECT counts FROM counted),
    (SELECT count(*) FROM filtered),
    COALESCE((
      SELECT jsonb_agg(public.content_draft_row_json(d) ORDER BY d.updated_at DESC, d.id)
      FROM public.content_drafts d
      WHERE d.id IN (
        SELECT f.id FROM filtered f
        ORDER BY f.updated_at DESC, f.id
        OFFSET v_offset LIMIT v_limit
      )
    ), '[]'::jsonb)
  INTO v_counts, v_total, v_rows;

  RETURN jsonb_build_object('total', v_total, 'counts', v_counts, 'rows', v_rows);
END;
$$;

-- A campaign's drafts for its brand or an admin.
-- p_status: as my_content_drafts_page (default pending_review).
-- p_search: creator username or draft title. p_sort: oldest | newest
-- (by when the draft last went into review).
-- Returns { total, counts, rows: [... + creator + record] }, or NULL when the
-- caller can't manage the campaign.
CREATE OR REPLACE FUNCTION public.campaign_content_drafts_page(
  p_contest_id uuid,
  p_status text,
  p_search text,
  p_sort text,
  p_offset integer,
  p_limit integer
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_status text := COALESCE(NULLIF(btrim(COALESCE(p_status, '')), ''), 'pending_review');
  v_search text := lower(NULLIF(btrim(COALESCE(p_search, '')), ''));
  v_sort   text := CASE WHEN p_sort = 'newest' THEN 'newest' ELSE 'oldest' END;
  v_offset integer := GREATEST(COALESCE(p_offset, 0), 0);
  v_limit  integer := LEAST(GREATEST(COALESCE(p_limit, 30), 1), 100);
  v_counts jsonb;
  v_total  bigint;
  v_rows   jsonb;
BEGIN
  IF NOT public.can_manage_contest_access(p_contest_id) THEN
    RETURN NULL;
  END IF;

  WITH scoped AS (
    SELECT d.*, public.content_draft_display_status(d) AS display_status
    FROM public.content_drafts d
    WHERE d.contest_id = p_contest_id
  ),
  counted AS (
    SELECT COALESCE(jsonb_object_agg(s.display_status, s.n), '{}'::jsonb) AS counts
    FROM (SELECT x.display_status, count(*) AS n FROM scoped x GROUP BY x.display_status) s
  ),
  filtered AS (
    SELECT x.*
    FROM scoped x
    LEFT JOIN public.users u ON u.id = x.creator_id
    LEFT JOIN public.content_draft_versions v ON v.id = x.current_version_id
    WHERE (v_status = 'all'
           OR (v_status = 'approved_all' AND x.status = 'approved')
           OR x.display_status = v_status)
      AND (
        v_search IS NULL
        OR strpos(lower(COALESCE(u.username, '')), v_search) > 0
        OR strpos(lower(COALESCE(v.title, '')), v_search) > 0
      )
  ),
  page AS (
    SELECT f.*
    FROM filtered f
    ORDER BY
      CASE WHEN v_sort = 'oldest' THEN f.submitted_at END ASC,
      CASE WHEN v_sort = 'newest' THEN f.submitted_at END DESC,
      f.id
    OFFSET v_offset LIMIT v_limit
  ),
  records AS (
    SELECT * FROM public.creator_draft_records(ARRAY(SELECT DISTINCT p.creator_id FROM page p))
  )
  SELECT
    (SELECT counts FROM counted),
    (SELECT count(*) FROM filtered),
    COALESCE((
      SELECT jsonb_agg(
        public.content_draft_row_json(d)
          || jsonb_build_object(
            'creator', jsonb_build_object(
              'id', u.id,
              'username', u.username,
              'full_name', u.full_name,
              'profile_picture_url', u.profile_picture_url
            ),
            'record', CASE WHEN r.creator_id IS NULL THEN NULL ELSE jsonb_build_object(
              'approved', r.approved,
              'rejected', r.rejected,
              'revisions', r.revisions,
              'withdrawn', r.withdrawn,
              'draft_trust', r.draft_trust
            ) END
          )
        ORDER BY
          CASE WHEN v_sort = 'oldest' THEN d.submitted_at END ASC,
          CASE WHEN v_sort = 'newest' THEN d.submitted_at END DESC,
          d.id
      )
      FROM public.content_drafts d
      JOIN page p ON p.id = d.id
      LEFT JOIN public.users u ON u.id = d.creator_id
      LEFT JOIN records r ON r.creator_id = d.creator_id
    ), '[]'::jsonb)
  INTO v_counts, v_total, v_rows;

  RETURN jsonb_build_object(
    'total', v_total,
    'counts', v_counts,
    'rows', v_rows,
    'review_before_posting', COALESCE(
      (SELECT c.review_before_posting FROM public.contests c WHERE c.id = p_contest_id),
      false
    )
  );
END;
$$;

-- Everything the draft page needs: draft, versions, timeline, linked posts,
-- and which actions the caller can take. NULL when the caller can't see it.
CREATE OR REPLACE FUNCTION public.content_draft_detail(p_draft_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid       uuid := auth.uid();
  v_draft     public.content_drafts;
  v_contest   record;
  v_role      text;
  v_display   text;
  v_posted    boolean;
  v_campaign  text;
  v_max_rev   integer;
  v_result    jsonb;
BEGIN
  IF v_uid IS NULL THEN
    RETURN NULL;
  END IF;
  SELECT * INTO v_draft FROM public.content_drafts d WHERE d.id = p_draft_id;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  SELECT c.id, c.advertiser_id, c.draft_max_revisions INTO v_contest
  FROM public.contests c WHERE c.id = v_draft.contest_id;

  IF v_draft.creator_id = v_uid THEN
    v_role := 'creator';
  ELSIF public.can_manage_contest_access(v_draft.contest_id) THEN
    v_role := CASE WHEN v_contest.advertiser_id = v_uid THEN 'brand' ELSE 'admin' END;
  ELSE
    RETURN NULL;
  END IF;

  v_display := public.content_draft_display_status(v_draft);
  v_posted := v_display = 'posted';
  v_max_rev := v_contest.draft_max_revisions;
  v_campaign := CASE WHEN v_role = 'creator'
    THEN public.content_draft_campaign_check(v_draft.contest_id, v_uid) END;

  v_result := public.content_draft_row_json(v_draft) || jsonb_build_object(
    'viewer_role', v_role,
    'max_revisions', v_max_rev,
    'versions', COALESCE((
      SELECT jsonb_agg(
        jsonb_build_object(
          'id', v.id,
          'version_no', v.version_no,
          'title', v.title,
          'caption', v.caption,
          'hashtags', to_jsonb(v.hashtags),
          'creator_note', v.creator_note,
          'poster_path', v.poster_path,
          'storage_path', v.storage_path,
          'mime_type', v.mime_type,
          'size_bytes', v.size_bytes,
          'duration_sec', v.duration_sec,
          'width', v.width,
          'height', v.height,
          'created_at', v.created_at
        )
        ORDER BY v.version_no
      )
      FROM public.content_draft_versions v
      WHERE v.draft_id = v_draft.id
    ), '[]'::jsonb),
    'events', COALESCE((
      SELECT jsonb_agg(
        jsonb_build_object(
          'id', e.id,
          'kind', e.kind,
          'actor_role', e.actor_role,
          'actor_id', e.actor_id,
          'actor_name', CASE e.actor_role
            WHEN 'creator' THEN (SELECT u.username FROM public.users u WHERE u.id = e.actor_id)
            WHEN 'brand' THEN public.content_draft_brand_name(v_draft.contest_id)
            WHEN 'admin' THEN 'Game of Creators team'
          END,
          'is_me', e.actor_id IS NOT DISTINCT FROM v_uid,
          'body', e.body,
          'version_id', e.version_id,
          'version_no', (SELECT v.version_no FROM public.content_draft_versions v WHERE v.id = e.version_id),
          'submission_id', e.submission_id,
          'meta', e.meta,
          'created_at', e.created_at
        )
        ORDER BY e.created_at, e.id
      )
      FROM public.content_draft_events e
      WHERE e.draft_id = v_draft.id
    ), '[]'::jsonb),
    'can', jsonb_build_object(
      'revise', v_role = 'creator' AND v_draft.status = 'revision_requested' AND v_campaign IS NULL,
      'withdraw', v_role = 'creator' AND NOT v_posted
        AND v_draft.status IN ('pending_review', 'revision_requested', 'approved'),
      'post', v_role = 'creator' AND v_draft.status = 'approved'
        AND v_campaign IS DISTINCT FROM 'ended' AND v_campaign IS DISTINCT FROM 'no_access',
      'comment', v_draft.status <> 'withdrawn',
      'review', v_role <> 'creator' AND v_draft.status = 'pending_review',
      'revoke', v_role <> 'creator' AND v_draft.status = 'approved' AND NOT v_posted,
      'request_revision', v_role <> 'creator'
        AND (v_draft.status = 'pending_review' OR (v_draft.status = 'approved' AND NOT v_posted))
        AND (v_max_rev IS NULL OR v_draft.revision_count < v_max_rev)
    ),
    'campaign_block', v_campaign
  );

  IF v_role <> 'creator' THEN
    v_result := v_result || jsonb_build_object(
      'creator', (
        SELECT jsonb_build_object(
          'id', u.id,
          'username', u.username,
          'full_name', u.full_name,
          'profile_picture_url', u.profile_picture_url
        )
        FROM public.users u WHERE u.id = v_draft.creator_id
      ),
      'record', (
        SELECT jsonb_build_object(
          'approved', r.approved,
          'rejected', r.rejected,
          'revisions', r.revisions,
          'withdrawn', r.withdrawn,
          'draft_trust', r.draft_trust
        )
        FROM public.creator_draft_records(ARRAY[v_draft.creator_id]) r
      )
    );
  END IF;

  RETURN v_result;
END;
$$;

-- Review-before-posting state of one campaign for the signed-in creator:
-- whether it is on, whether they can send drafts now (and why not), their
-- counts and the campaign's limits.
CREATE OR REPLACE FUNCTION public.content_draft_campaign_status(p_contest_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid     uuid := auth.uid();
  v_contest record;
  v_counts  jsonb;
  v_open    integer;
  v_rejected integer;
  v_block   text;
BEGIN
  SELECT c.id, c.review_before_posting, c.draft_max_open, c.draft_max_revisions,
         c.draft_max_rejections, c.moderation_status
  INTO v_contest
  FROM public.contests c
  WHERE c.id = p_contest_id;

  IF NOT FOUND OR v_uid IS NULL OR NOT public.can_access_contest(p_contest_id) THEN
    RETURN jsonb_build_object('review_before_posting', false);
  END IF;

  SELECT
    COALESCE(jsonb_object_agg(s.display_status, s.n), '{}'::jsonb),
    COALESCE(sum(s.n) FILTER (WHERE s.display_status IN ('pending_review', 'revision_requested')), 0),
    COALESCE(sum(s.n) FILTER (WHERE s.display_status = 'rejected'), 0)
  INTO v_counts, v_open, v_rejected
  FROM (
    SELECT public.content_draft_display_status(d) AS display_status, count(*) AS n
    FROM public.content_drafts d
    WHERE d.contest_id = p_contest_id AND d.creator_id = v_uid
    GROUP BY 1
  ) s;

  v_block := public.content_draft_campaign_check(p_contest_id, v_uid);
  IF v_block IS NULL AND v_contest.draft_max_rejections IS NOT NULL
     AND v_rejected >= v_contest.draft_max_rejections THEN
    v_block := 'rejection_limit_reached';
  END IF;
  IF v_block IS NULL AND v_contest.draft_max_open IS NOT NULL
     AND v_open >= v_contest.draft_max_open THEN
    v_block := 'open_limit_reached';
  END IF;

  RETURN jsonb_build_object(
    'review_before_posting', COALESCE(v_contest.review_before_posting, false),
    'can_upload', v_block IS NULL,
    'block_reason', v_block,
    'counts', v_counts,
    'open_count', v_open,
    'rejected_count', v_rejected,
    'max_open', v_contest.draft_max_open,
    'max_revisions', v_contest.draft_max_revisions,
    'max_rejections', v_contest.draft_max_rejections
  );
END;
$$;

