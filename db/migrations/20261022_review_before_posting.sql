-- Creates a draft (version 1) from a finished upload and sends it for review.
-- Calling it again with the same draft id returns 'submitted' without changes.
CREATE OR REPLACE FUNCTION public.create_content_draft(
  p_draft_id uuid,
  p_contest_id uuid,
  p_version_id uuid,
  p_storage_path text,
  p_poster_path text,
  p_title text,
  p_caption text,
  p_hashtags text[],
  p_note text,
  p_duration_sec numeric,
  p_width integer,
  p_height integer
)
RETURNS TABLE (result text, draft_id uuid, detail text)
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
#variable_conflict use_column
DECLARE
  v_uid      uuid := auth.uid();
  v_existing record;
  v_contest  record;
  v_check    text;
  v_error    text;
  v_open     integer;
  v_rejected integer;
  v_title    text := btrim(COALESCE(p_title, ''));
BEGIN
  IF v_uid IS NULL THEN
    RETURN QUERY SELECT 'not_signed_in'::text, NULL::uuid, NULL::text;
    RETURN;
  END IF;
  IF p_draft_id IS NULL OR p_version_id IS NULL OR p_contest_id IS NULL THEN
    RETURN QUERY SELECT 'invalid_input'::text, NULL::uuid, 'id'::text;
    RETURN;
  END IF;

  -- One creator's sends to one campaign are handled one at a time, so the
  -- limits below can't be overrun by parallel uploads.
  PERFORM pg_advisory_xact_lock(
    hashtextextended('content_draft:' || v_uid::text || ':' || p_contest_id::text, 0)
  );

  SELECT d.creator_id, d.contest_id INTO v_existing
  FROM public.content_drafts d
  WHERE d.id = p_draft_id;
  IF FOUND THEN
    IF v_existing.creator_id = v_uid AND v_existing.contest_id = p_contest_id THEN
      RETURN QUERY SELECT 'submitted'::text, p_draft_id, NULL::text;
    ELSE
      RETURN QUERY SELECT 'conflict'::text, NULL::uuid, NULL::text;
    END IF;
    RETURN;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.users u WHERE u.id = v_uid AND u.user_type = 'creator'
  ) THEN
    RETURN QUERY SELECT 'not_creator'::text, NULL::uuid, NULL::text;
    RETURN;
  END IF;

  v_check := public.content_draft_campaign_check(p_contest_id, v_uid);
  IF v_check IS NOT NULL THEN
    RETURN QUERY SELECT v_check, NULL::uuid, NULL::text;
    RETURN;
  END IF;

  SELECT c.id, c.title, c.advertiser_id, c.draft_max_open, c.draft_max_rejections
  INTO v_contest
  FROM public.contests c
  WHERE c.id = p_contest_id;

  SELECT
    count(*) FILTER (WHERE d.status IN ('pending_review', 'revision_requested')),
    count(*) FILTER (WHERE d.status = 'rejected')
  INTO v_open, v_rejected
  FROM public.content_drafts d
  WHERE d.contest_id = p_contest_id AND d.creator_id = v_uid;

  IF v_contest.draft_max_rejections IS NOT NULL AND v_rejected >= v_contest.draft_max_rejections THEN
    RETURN QUERY SELECT 'rejection_limit_reached'::text, NULL::uuid, v_contest.draft_max_rejections::text;
    RETURN;
  END IF;
  IF v_contest.draft_max_open IS NOT NULL AND v_open >= v_contest.draft_max_open THEN
    RETURN QUERY SELECT 'open_limit_reached'::text, NULL::uuid, v_contest.draft_max_open::text;
    RETURN;
  END IF;

  v_error := public.content_draft_version_input_error(
    v_uid, p_draft_id, p_version_id, p_storage_path, p_title, p_caption,
    p_hashtags, p_note, p_duration_sec, p_width, p_height
  );
  IF v_error IS NOT NULL THEN
    RETURN QUERY SELECT split_part(v_error, ':', 1), NULL::uuid, NULLIF(split_part(v_error, ':', 2), '');
    RETURN;
  END IF;

  INSERT INTO public.content_drafts (id, contest_id, creator_id, current_version_id)
  VALUES (p_draft_id, p_contest_id, v_uid, p_version_id);

  INSERT INTO public.content_draft_versions (
    id, draft_id, version_no, storage_path, poster_path, mime_type, size_bytes,
    duration_sec, width, height, title, caption, hashtags, creator_note
  )
  SELECT
    p_version_id,
    p_draft_id,
    1,
    p_storage_path,
    public.content_draft_poster_path(v_uid, p_draft_id, p_version_id, p_poster_path),
    f.mime_type,
    f.size_bytes,
    round(p_duration_sec, 2),
    p_width,
    p_height,
    v_title,
    NULLIF(btrim(COALESCE(p_caption, '')), ''),
    public.content_draft_clean_hashtags(p_hashtags),
    NULLIF(btrim(COALESCE(p_note, '')), '')
  FROM public.content_draft_object_info(p_storage_path) f;

  INSERT INTO public.content_draft_events (draft_id, version_id, actor_id, actor_role, kind, body)
  VALUES (p_draft_id, p_version_id, v_uid, 'creator', 'submitted', NULLIF(btrim(COALESCE(p_note, '')), ''));

  PERFORM public.content_draft_notify(
    v_contest.advertiser_id,
    p_contest_id,
    'content_draft_submitted',
    'Drafts to review',
    'Creators sent drafts for review in ' || COALESCE(NULLIF(btrim(v_contest.title), ''), 'your campaign')
      || '. Open the Drafts tab to review them.'
  );

  RETURN QUERY SELECT 'submitted'::text, p_draft_id, NULL::text;
END;
$$;

