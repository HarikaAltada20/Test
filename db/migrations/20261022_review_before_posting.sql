  creator_id          uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status              text NOT NULL DEFAULT 'pending_review'
                      CHECK (status IN ('pending_review', 'revision_requested', 'approved', 'rejected', 'withdrawn')),
  current_version_id  uuid,
  version_count       integer NOT NULL DEFAULT 1 CHECK (version_count >= 1),
  -- Revision rounds the brand has asked for (counts toward draft_max_revisions).
  revision_count      integer NOT NULL DEFAULT 0 CHECK (revision_count >= 0),
  approved_version_id uuid,
  approved_at         timestamptz,
  decided_by          uuid REFERENCES public.users(id) ON DELETE SET NULL,
  decided_at          timestamptz,
  -- Feedback behind the current status (revision request, rejection or approval note).
