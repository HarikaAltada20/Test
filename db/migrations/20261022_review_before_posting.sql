-- Validates a draft's text fields and uploaded file. NULL when valid,
-- otherwise 'invalid_input:<field>', 'invalid_file:<why>' or 'upload_missing'.
CREATE OR REPLACE FUNCTION public.content_draft_version_input_error(
  p_creator_id uuid,
  p_draft_id uuid,
  p_version_id uuid,
  p_storage_path text,
  p_title text,
  p_caption text,
  p_hashtags text[],
  p_note text,
  p_duration_sec numeric,
  p_width integer,
  p_height integer
)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_ext  text := lower(substring(COALESCE(p_storage_path, '') FROM '\.([A-Za-z0-9]+)$'));
  v_file record;
BEGIN
  IF length(btrim(COALESCE(p_title, ''))) NOT BETWEEN 1 AND 200 THEN
    RETURN 'invalid_input:title';
  END IF;
  IF length(btrim(COALESCE(p_caption, ''))) > 2200 THEN
    RETURN 'invalid_input:caption';
  END IF;
  IF length(btrim(COALESCE(p_note, ''))) > 1000 THEN
    RETURN 'invalid_input:note';
  END IF;
  IF cardinality(public.content_draft_clean_hashtags(p_hashtags)) > 30 THEN
    RETURN 'invalid_input:hashtags';
  END IF;
  IF p_duration_sec IS NOT NULL AND (p_duration_sec <= 0 OR p_duration_sec > 181) THEN
    RETURN 'invalid_input:duration';
  END IF;
  IF (p_width IS NOT NULL AND (p_width <= 0 OR p_width > 10000))
     OR (p_height IS NOT NULL AND (p_height <= 0 OR p_height > 10000)) THEN
    RETURN 'invalid_input:dimensions';
  END IF;

  IF v_ext IS NULL OR v_ext NOT IN ('mp4', 'mov', 'webm')
     OR p_storage_path IS DISTINCT FROM
        (p_creator_id::text || '/' || p_draft_id::text || '/' || p_version_id::text || '.' || v_ext) THEN
    RETURN 'invalid_file:path';
  END IF;

  SELECT * INTO v_file FROM public.content_draft_object_info(p_storage_path);
  IF NOT FOUND OR v_file.size_bytes IS NULL THEN
    RETURN 'upload_missing';
  END IF;
  IF v_file.mime_type NOT IN ('video/mp4', 'video/quicktime', 'video/webm') THEN
    RETURN 'invalid_file:type';
  END IF;
  IF v_file.size_bytes <= 0 OR v_file.size_bytes > 104857600 THEN
    RETURN 'invalid_file:size';
  END IF;
  RETURN NULL;
END;
$$;

-- The poster image if it was uploaded where expected, otherwise NULL.
CREATE OR REPLACE FUNCTION public.content_draft_poster_path(
  p_creator_id uuid,
  p_draft_id uuid,
  p_version_id uuid,
  p_poster_path text
)
RETURNS text
LANGUAGE sql
