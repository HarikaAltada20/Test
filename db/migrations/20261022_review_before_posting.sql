-- Approved / rejected / revision counts across all campaigns, and a draft
-- trust score on the same scale as the submission trust score:
-- (approved - rejected) / approved x 100, clamped to 0-100; with no
-- approvals it is 100 when nothing was rejected, otherwise 0.
CREATE OR REPLACE FUNCTION public.creator_draft_records(p_creator_ids uuid[])
RETURNS TABLE (
  creator_id  uuid,
  approved    integer,
  rejected    integer,
  revisions   integer,
  withdrawn   integer,
  draft_trust integer
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  WITH counts AS (
    SELECT
      d.creator_id,
      count(*) FILTER (WHERE d.status = 'approved')::integer AS approved,
      count(*) FILTER (WHERE d.status = 'rejected')::integer AS rejected,
      COALESCE(sum(d.revision_count), 0)::integer AS revisions,
      count(*) FILTER (WHERE d.status = 'withdrawn')::integer AS withdrawn
    FROM public.content_drafts d
    WHERE d.creator_id = ANY (COALESCE(p_creator_ids, ARRAY[]::uuid[]))
    GROUP BY d.creator_id
  )
  SELECT
    c.creator_id,
    c.approved,
    c.rejected,
    c.revisions,
    c.withdrawn,
    CASE
      WHEN c.approved = 0 THEN CASE WHEN c.rejected > 0 THEN 0 ELSE 100 END
      ELSE GREATEST(0, LEAST(100, round(((c.approved - c.rejected)::numeric / c.approved) * 100)))::integer
    END
  FROM counts c;
$$;

-- ---------------------------------------------------------------------------
-- 7. Submissions gate
-- ---------------------------------------------------------------------------

-- With review before posting on, a submission needs an approved draft of the
-- same creator and campaign, at most one post per platform per draft, and a
-- platform publish time (when sent) that isn't before the approval.
-- Platform admins and the service role (admin tools, backfills) may add a
-- submission without a draft; it is tagged metadata.review_bypass. A draft
-- they do name is still checked. Changing which video or draft a linked post
-- points at is refused for creators.
CREATE OR REPLACE FUNCTION public.enforce_submission_draft_approval()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid        uuid := auth.uid();
  v_privileged boolean;
  v_review     boolean;
  v_draft      record;
BEGIN
  IF TG_OP = 'UPDATE'
     AND NEW.draft_id IS NOT DISTINCT FROM OLD.draft_id
     AND NEW.draft_version_id IS NOT DISTINCT FROM OLD.draft_version_id
     AND NEW.contest_id IS NOT DISTINCT FROM OLD.contest_id
     AND NEW.creator_id IS NOT DISTINCT FROM OLD.creator_id
     AND NEW.platform IS NOT DISTINCT FROM OLD.platform
     AND NEW.video_id IS NOT DISTINCT FROM OLD.video_id
     AND NEW.content_link IS NOT DISTINCT FROM OLD.content_link
     AND NEW.platform_published_at IS NOT DISTINCT FROM OLD.platform_published_at THEN
    RETURN NEW;
  END IF;

  v_privileged := v_uid IS NULL OR public.is_platform_admin(v_uid);

  IF TG_OP = 'UPDATE' THEN
    -- A deleted draft or version clears its links (ON DELETE SET NULL).
    IF NEW.draft_id IS NULL AND OLD.draft_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM public.content_drafts d WHERE d.id = OLD.draft_id) THEN
      RETURN NEW;
    END IF;
    IF NEW.draft_version_id IS NULL AND OLD.draft_version_id IS NOT NULL
       AND NEW.draft_id IS NOT DISTINCT FROM OLD.draft_id
       AND NOT EXISTS (SELECT 1 FROM public.content_draft_versions v WHERE v.id = OLD.draft_version_id) THEN
      RETURN NEW;
    END IF;
    IF v_privileged THEN
      RETURN NEW;
    END IF;
    -- Creators link a draft only when adding the post, so an older post
    -- can't be attached to a newer approval.
    IF OLD.draft_id IS NOT NULL OR NEW.draft_id IS NOT NULL THEN
      RAISE EXCEPTION 'draft_link_locked: A post linked to an approved draft can''t be changed'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  SELECT COALESCE(c.review_before_posting, false) INTO v_review
  FROM public.contests c
  WHERE c.id = NEW.contest_id;

  IF NEW.draft_id IS NULL THEN
    IF COALESCE(v_review, false) THEN
      IF NOT v_privileged THEN
        RAISE EXCEPTION 'draft_required: This campaign reviews videos before they are posted. Choose an approved draft'
          USING ERRCODE = 'check_violation';
      END IF;
      -- Admin or server added it without a draft: say so on the submission.
      IF TG_OP = 'INSERT' THEN
        NEW.metadata := COALESCE(NEW.metadata, '{}'::jsonb)
          || jsonb_build_object('review_bypass', jsonb_build_object('by', v_uid, 'at', now()));
      END IF;
    END IF;
    NEW.draft_version_id := NULL;
    RETURN NEW;
  END IF;

  -- Locked so two tabs can't use the same approval at the same time.
  SELECT d.id, d.contest_id, d.creator_id, d.status, d.approved_version_id, d.approved_at
  INTO v_draft
  FROM public.content_drafts d
  WHERE d.id = NEW.draft_id
  FOR UPDATE;

  IF NOT FOUND
     OR v_draft.creator_id IS DISTINCT FROM NEW.creator_id
     OR v_draft.contest_id IS DISTINCT FROM NEW.contest_id THEN
    RAISE EXCEPTION 'draft_not_found: That draft isn''t yours or belongs to another campaign'
      USING ERRCODE = 'check_violation';
  END IF;

  IF v_draft.status <> 'approved' THEN
    RAISE EXCEPTION 'draft_not_approved: Only an approved draft can be posted'
      USING ERRCODE = 'check_violation';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.submissions s
    WHERE s.draft_id = NEW.draft_id
      AND lower(COALESCE(s.platform, '')) = lower(COALESCE(NEW.platform, ''))
      AND s.id IS DISTINCT FROM NEW.id
  ) THEN
    RAISE EXCEPTION 'draft_already_posted: This draft is already linked to a post on this platform'
      USING ERRCODE = 'check_violation';
  END IF;

  -- Two minutes of slack for clock differences.
  IF NEW.platform_published_at IS NOT NULL
     AND NEW.platform_published_at < v_draft.approved_at - interval '2 minutes' THEN
    RAISE EXCEPTION 'draft_posted_before_approval: This post went live before the draft was approved'
      USING ERRCODE = 'check_violation';
  END IF;

  NEW.draft_version_id := v_draft.approved_version_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS submissions_enforce_draft_approval ON public.submissions;
CREATE TRIGGER submissions_enforce_draft_approval
  BEFORE INSERT OR UPDATE OF
    draft_id, draft_version_id, contest_id, creator_id, platform, video_id, content_link, platform_published_at
  ON public.submissions
  FOR EACH ROW
  EXECUTE FUNCTION public.enforce_submission_draft_approval();

-- Adds the "posted" step to the draft's history.
CREATE OR REPLACE FUNCTION public.content_draft_record_post()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
BEGIN
  IF NEW.draft_id IS NULL OR (TG_OP = 'UPDATE' AND NEW.draft_id IS NOT DISTINCT FROM OLD.draft_id) THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.content_draft_events
    (draft_id, version_id, actor_id, actor_role, kind, submission_id, meta)
  VALUES (
    NEW.draft_id,
    NEW.draft_version_id,
