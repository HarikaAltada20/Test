  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'contests_draft_limits_valid'
  ) THEN
    ALTER TABLE public.contests
      ADD CONSTRAINT contests_draft_limits_valid CHECK (
        (draft_max_open IS NULL OR draft_max_open BETWEEN 1 AND 500)
        AND (draft_max_revisions IS NULL OR draft_max_revisions BETWEEN 0 AND 50)
        AND (draft_max_rejections IS NULL OR draft_max_rejections BETWEEN 1 AND 500)
      );
  END IF;
END;
$$;

COMMENT ON COLUMN public.contests.review_before_posting IS
  'Creators upload each video as a draft for approval before posting; only links tied to an approved draft are accepted.';
COMMENT ON COLUMN public.contests.draft_max_open IS
  'Review before posting: drafts a creator may have open (in review or revision requested) at once. NULL = no limit.';
COMMENT ON COLUMN public.contests.draft_max_revisions IS
  'Review before posting: revision rounds per draft. After this the brand can only approve or reject. NULL = no limit.';
COMMENT ON COLUMN public.contests.draft_max_rejections IS
  'Review before posting: rejected drafts per creator before new drafts are blocked. NULL = no limit.';

