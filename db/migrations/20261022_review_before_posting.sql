  ADD COLUMN IF NOT EXISTS draft_max_open integer DEFAULT 20,
  ADD COLUMN IF NOT EXISTS draft_max_revisions integer DEFAULT 5,
  ADD COLUMN IF NOT EXISTS draft_max_rejections integer;

DO $$
