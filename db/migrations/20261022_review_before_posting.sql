-- Hashtags without '#', no spaces, 1-100 characters, de-duplicated
-- case-insensitively (first spelling wins), in the order given.
CREATE OR REPLACE FUNCTION public.content_draft_clean_hashtags(p_tags text[])
RETURNS text[]
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  WITH cleaned AS (
    SELECT regexp_replace(btrim(x), '^#+', '') AS tag, pos
    FROM unnest(COALESCE(p_tags, ARRAY[]::text[])) WITH ORDINALITY AS u(x, pos)
  ),
  valid AS (
    SELECT tag, pos, row_number() OVER (PARTITION BY lower(tag) ORDER BY pos) AS rn
    FROM cleaned
    WHERE tag ~ '^[^[:space:]#]{1,100}$'
  )
  SELECT COALESCE(array_agg(tag ORDER BY pos), ARRAY[]::text[])
  FROM valid
  WHERE rn = 1;
$$;

-- Size and type of an uploaded draft file, or no row when it doesn't exist.
CREATE OR REPLACE FUNCTION public.content_draft_object_info(p_path text)
RETURNS TABLE (size_bytes bigint, mime_type text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT
    CASE
      WHEN o.metadata ->> 'size' ~ '^[0-9]{1,15}$' THEN (o.metadata ->> 'size')::bigint
      WHEN o.metadata ->> 'contentLength' ~ '^[0-9]{1,15}$' THEN (o.metadata ->> 'contentLength')::bigint
    END,
    lower(COALESCE(o.metadata ->> 'mimetype', ''))
  FROM storage.objects o
  WHERE o.bucket_id = 'content-drafts' AND o.name = p_path
  LIMIT 1;
$$;

-- NULL when the creator may send drafts (or revisions) to the campaign now,
-- otherwise the reason as a result code. Mirrors the submission rules:
-- published and running, on the access list for Private/Restricted
-- campaigns, and meeting the creator requirements unless listed creators
-- skip them.
CREATE OR REPLACE FUNCTION public.content_draft_campaign_check(p_contest_id uuid, p_creator_id uuid)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_contest public.contests;
  v_profile public.creator_profiles;
  v_listed  boolean;
BEGIN
  SELECT * INTO v_contest FROM public.contests c WHERE c.id = p_contest_id;
  IF NOT FOUND OR v_contest.moderation_status IS DISTINCT FROM 'published'::public.contest_moderation_status_enum THEN
    RETURN 'not_found';
  END IF;
  IF NOT COALESCE(v_contest.review_before_posting, false) THEN
    RETURN 'review_not_enabled';
  END IF;
  IF v_contest.start_date IS NULL OR v_contest.end_date IS NULL OR now() < v_contest.start_date THEN
    RETURN 'not_started';
  END IF;
  IF now() >= v_contest.end_date THEN
    RETURN 'ended';
  END IF;

  v_listed := EXISTS (
    SELECT 1 FROM public.contest_access_list a
    WHERE a.contest_id = p_contest_id AND a.user_id = p_creator_id
  );
  IF COALESCE(v_contest.access_mode, 'public') <> 'public' AND NOT v_listed THEN
    RETURN 'no_access';
  END IF;
  IF v_listed AND COALESCE(v_contest.access_list_skips_requirements, false) THEN
    RETURN NULL;
  END IF;

  -- Only listed creators skip requirements (as on submit).
  v_contest.access_list_skips_requirements := false;
  SELECT * INTO v_profile FROM public.creator_profiles p WHERE p.id = p_creator_id;
  IF public.contest_application_requirement_state(v_contest, v_profile) = 'below' THEN
    RETURN 'requirements_not_met';
  END IF;
  RETURN NULL;
END;
$$;

