-- Drafts whose campaign ended more than p_days ago and still have files.
CREATE OR REPLACE FUNCTION public.content_draft_files_due(p_days integer, p_limit integer)
RETURNS TABLE (draft_id uuid, paths text[])
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT
    d.id,
    ARRAY(
      SELECT p
      FROM public.content_draft_versions v,
           LATERAL unnest(ARRAY[v.storage_path, v.poster_path]) AS p
      WHERE v.draft_id = d.id AND p IS NOT NULL
    )
  FROM public.content_drafts d
  JOIN public.contests c ON c.id = d.contest_id
  WHERE d.files_purged_at IS NULL
    AND c.end_date IS NOT NULL
    AND c.end_date < now() - make_interval(days => GREATEST(COALESCE(p_days, 30), 0))
  ORDER BY c.end_date, d.id
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 100), 1), 500);
$$;

CREATE OR REPLACE FUNCTION public.mark_content_draft_files_purged(p_draft_ids uuid[])
RETURNS integer
LANGUAGE sql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
  WITH done AS (
    UPDATE public.content_drafts d
    SET files_purged_at = now()
    WHERE d.id = ANY (COALESCE(p_draft_ids, ARRAY[]::uuid[])) AND d.files_purged_at IS NULL
    RETURNING 1
  )
  SELECT count(*)::integer FROM done;
$$;

-- Uploads older than p_hours that never became a draft version (abandoned or
-- refused at "send").
CREATE OR REPLACE FUNCTION public.content_draft_orphan_files(p_hours integer, p_limit integer)
RETURNS TABLE (path text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT o.name
  FROM storage.objects o
  WHERE o.bucket_id = 'content-drafts'
    AND o.created_at < now() - make_interval(hours => GREATEST(COALESCE(p_hours, 24), 1))
    AND NOT EXISTS (SELECT 1 FROM public.content_draft_versions v WHERE v.storage_path = o.name)
    AND NOT EXISTS (SELECT 1 FROM public.content_draft_versions v WHERE v.poster_path = o.name)
  ORDER BY o.created_at
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 200), 1), 1000);
$$;

-- Drafts left in "revision requested" with no new version for p_days are
-- closed so they stop holding an open slot.
CREATE OR REPLACE FUNCTION public.expire_stale_content_drafts(p_days integer)
RETURNS integer
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_count integer;
BEGIN
  WITH expired AS (
    UPDATE public.content_drafts d
    SET status = 'withdrawn', updated_at = now()
    WHERE d.status = 'revision_requested'
      AND d.decided_at < now() - make_interval(days => GREATEST(COALESCE(p_days, 30), 1))
    RETURNING d.id, d.current_version_id
  ),
  logged AS (
    INSERT INTO public.content_draft_events (draft_id, version_id, actor_role, kind, body)
    SELECT e.id, e.current_version_id, 'system', 'expired',
           'Closed after ' || GREATEST(COALESCE(p_days, 30), 1) || ' days without a revision.'
    FROM expired e
    RETURNING 1
  )
  SELECT count(*)::integer INTO v_count FROM logged;
  RETURN v_count;
END;
$$;

