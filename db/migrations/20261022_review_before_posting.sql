-- Review before posting: brands approve a creator's video before it is posted.
--
-- When contests.review_before_posting is on, creators upload the raw video to
-- GoC as a draft. The brand (or an admin) then:
--   approve           -> the creator may post that exact version and submit its link
--   request_revision  -> the creator uploads a new version in the SAME draft
--   reject            -> final for that draft; the creator can start a new one
--
-- Tables
--   content_drafts          one row per draft (the review thread)
--   content_draft_versions  one row per uploaded file; never overwritten
--   content_draft_events    the conversation and audit log (decisions, comments, posts)
--
-- Enforcement lives in the database because submissions are inserted from the
-- browser: the submissions trigger below refuses a published link that isn't
-- tied to an approved draft of the same creator and campaign, and allows one
-- linked post per platform per draft. Drafts never count toward views,
-- earnings, payouts, trust score or submission counts.
--
-- Draft files live in the private 'content-drafts' storage bucket under
-- {creator_id}/{draft_id}/{version_id}.{mp4|mov|webm}. Creators can only add
-- files under their own folder and can't overwrite or delete them; playback
-- goes through short-lived signed URLs issued by the API.
--
-- Apply after:
--   db/migrations/20261020_campaign_access_final.sql
--   db/migrations/20261021_content_draft_notification_types.sql (run it on its own first)
-- Safe to re-run.

