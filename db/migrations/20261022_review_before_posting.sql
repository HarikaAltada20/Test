-- ---------------------------------------------------------------------------
-- 9. Review functions (campaign's brand or a platform admin)
-- ---------------------------------------------------------------------------

-- p_decision: approve | request_revision | reject. p_version_id must be the
-- version the reviewer watched: a newer version or someone else's decision
-- returns 'stale' instead of acting on the wrong video. On an approved draft
-- that hasn't been posted, request_revision / reject revoke the approval.
-- Repeating the decision that already stands returns it again unchanged.
CREATE OR REPLACE FUNCTION public.review_content_draft(
  p_draft_id uuid,
  p_version_id uuid,
  p_decision text,
  p_reason text DEFAULT NULL
)
RETURNS TABLE (result text, draft_id uuid, status text)
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
#variable_conflict use_column
DECLARE
  v_uid     uuid := auth.uid();
  v_draft   public.content_drafts;
  v_reason  text := NULLIF(btrim(COALESCE(p_reason, '')), '');
  v_contest record;
  v_role    text;
  v_new     text;
  v_revoke  boolean := false;
  v_title   text;
  v_brand   text;
  v_campaign text;
BEGIN
  IF p_decision IS NULL OR p_decision NOT IN ('approve', 'request_revision', 'reject') THEN
    RETURN QUERY SELECT 'invalid_decision'::text, p_draft_id, NULL::text;
    RETURN;
  END IF;

  SELECT * INTO v_draft FROM public.content_drafts d WHERE d.id = p_draft_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN QUERY SELECT 'not_found'::text, p_draft_id, NULL::text;
    RETURN;
  END IF;
  IF v_uid IS NULL OR NOT public.can_manage_contest_access(v_draft.contest_id) THEN
    RETURN QUERY SELECT 'forbidden'::text, p_draft_id, NULL::text;
    RETURN;
  END IF;
  IF v_reason IS NOT NULL AND length(v_reason) > 1000 THEN
    RETURN QUERY SELECT 'invalid_input'::text, p_draft_id, v_draft.status;
    RETURN;
  END IF;
  IF p_decision <> 'approve' AND v_reason IS NULL THEN
    RETURN QUERY SELECT 'reason_required'::text, p_draft_id, v_draft.status;
    RETURN;
  END IF;

  -- Same decision again (double click, retry): already done.
  IF (p_decision = 'approve' AND v_draft.status = 'approved'
        AND v_draft.approved_version_id IS NOT DISTINCT FROM p_version_id)
     OR (p_decision = 'request_revision' AND v_draft.status = 'revision_requested'
        AND v_draft.current_version_id IS NOT DISTINCT FROM p_version_id)
     OR (p_decision = 'reject' AND v_draft.status = 'rejected'
        AND v_draft.current_version_id IS NOT DISTINCT FROM p_version_id) THEN
    RETURN QUERY SELECT v_draft.status, p_draft_id, v_draft.status;
    RETURN;
  END IF;

  SELECT c.id, c.title, c.advertiser_id, c.draft_max_revisions INTO v_contest
  FROM public.contests c
  WHERE c.id = v_draft.contest_id;
  v_role := CASE WHEN v_contest.advertiser_id = v_uid THEN 'brand' ELSE 'admin' END;

  IF v_draft.status = 'pending_review' THEN
    IF p_version_id IS DISTINCT FROM v_draft.current_version_id THEN
      RETURN QUERY SELECT 'stale'::text, p_draft_id, v_draft.status;
      RETURN;
    END IF;
  ELSIF v_draft.status = 'approved' AND p_decision <> 'approve' THEN
    IF p_version_id IS DISTINCT FROM v_draft.approved_version_id THEN
      RETURN QUERY SELECT 'stale'::text, p_draft_id, v_draft.status;
      RETURN;
    END IF;
    IF EXISTS (SELECT 1 FROM public.submissions s WHERE s.draft_id = p_draft_id) THEN
      RETURN QUERY SELECT 'already_posted'::text, p_draft_id, v_draft.status;
      RETURN;
    END IF;
    v_revoke := true;
  ELSE
    RETURN QUERY SELECT 'stale'::text, p_draft_id, v_draft.status;
    RETURN;
  END IF;

  IF p_decision = 'request_revision'
     AND v_contest.draft_max_revisions IS NOT NULL
     AND v_draft.revision_count >= v_contest.draft_max_revisions THEN
    RETURN QUERY SELECT 'revision_limit_reached'::text, p_draft_id, v_draft.status;
    RETURN;
  END IF;

  v_new := CASE p_decision
    WHEN 'approve' THEN 'approved'
    WHEN 'request_revision' THEN 'revision_requested'
    ELSE 'rejected'
  END;

  UPDATE public.content_drafts d
  SET status = v_new,
      approved_version_id = CASE WHEN v_new = 'approved' THEN v_draft.current_version_id END,
      approved_at = CASE WHEN v_new = 'approved' THEN now() END,
      revision_count = d.revision_count + CASE WHEN v_new = 'revision_requested' THEN 1 ELSE 0 END,
      decided_by = v_uid,
      decided_at = now(),
      decision_reason = v_reason,
      updated_at = now()
  WHERE d.id = p_draft_id;

  INSERT INTO public.content_draft_events (draft_id, version_id, actor_id, actor_role, kind, body, meta)
  VALUES (
    p_draft_id,
    CASE WHEN v_revoke THEN v_draft.approved_version_id ELSE v_draft.current_version_id END,
    v_uid,
    v_role,
    CASE WHEN v_revoke THEN 'approval_revoked' ELSE v_new END,
    v_reason,
    CASE WHEN v_revoke THEN jsonb_build_object('to', v_new) END
  );

  SELECT v.title INTO v_title FROM public.content_draft_versions v WHERE v.id = v_draft.current_version_id;
  v_brand := public.content_draft_brand_name(v_draft.contest_id);
  v_campaign := COALESCE(NULLIF(btrim(v_contest.title), ''), 'the campaign');

  IF v_new = 'approved' THEN
    PERFORM public.content_draft_notify(
      v_draft.creator_id, v_draft.contest_id, 'content_draft_approved',
      'Draft approved: ' || COALESCE(v_title, 'your video'),
      v_brand || ' approved your draft for ' || v_campaign
        || '. Post this exact video, then submit the link.'
        || CASE WHEN v_reason IS NOT NULL THEN E'\n\nNote: ' || v_reason ELSE '' END
    );
  ELSIF v_new = 'revision_requested' THEN
    PERFORM public.content_draft_notify(
      v_draft.creator_id, v_draft.contest_id, 'content_draft_revision_requested',
      CASE WHEN v_revoke THEN 'Approval withdrawn: ' ELSE 'Changes requested: ' END || COALESCE(v_title, 'your video'),
      v_brand || ' asked for changes to your draft for ' || v_campaign || E':\n\n' || v_reason
    );
  ELSE
    PERFORM public.content_draft_notify(
      v_draft.creator_id, v_draft.contest_id, 'content_draft_rejected',
      CASE WHEN v_revoke THEN 'Approval withdrawn: ' ELSE 'Draft not approved: ' END || COALESCE(v_title, 'your video'),
      v_brand || ' didn''t approve your draft for ' || v_campaign || E'.\n\nReason: ' || v_reason
    );
  END IF;

  RETURN QUERY SELECT v_new, p_draft_id, v_new;
END;
$$;

-- A message in the draft's thread, from its creator or the campaign's brand
-- or an admin. Notifies the other side (one unread notification per campaign).
CREATE OR REPLACE FUNCTION public.comment_on_content_draft(p_draft_id uuid, p_body text)
RETURNS TABLE (result text, event_id uuid)
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
#variable_conflict use_column
DECLARE
  v_uid     uuid := auth.uid();
  v_body    text := btrim(COALESCE(p_body, ''));
  v_draft   public.content_drafts;
  v_contest record;
  v_role    text;
  v_id      uuid;
  v_name    text;
BEGIN
  IF v_uid IS NULL THEN
    RETURN QUERY SELECT 'not_signed_in'::text, NULL::uuid;
    RETURN;
  END IF;
  IF length(v_body) NOT BETWEEN 1 AND 2000 THEN
    RETURN QUERY SELECT 'invalid_input'::text, NULL::uuid;
    RETURN;
  END IF;

  SELECT * INTO v_draft FROM public.content_drafts d WHERE d.id = p_draft_id;
  IF NOT FOUND THEN
    RETURN QUERY SELECT 'not_found'::text, NULL::uuid;
    RETURN;
  END IF;

  SELECT c.title, c.advertiser_id INTO v_contest FROM public.contests c WHERE c.id = v_draft.contest_id;
  IF v_draft.creator_id = v_uid THEN
    v_role := 'creator';
  ELSIF public.can_manage_contest_access(v_draft.contest_id) THEN
    v_role := CASE WHEN v_contest.advertiser_id = v_uid THEN 'brand' ELSE 'admin' END;
  ELSE
    RETURN QUERY SELECT 'not_found'::text, NULL::uuid;
    RETURN;
  END IF;

  IF v_draft.status = 'withdrawn' THEN
    RETURN QUERY SELECT 'invalid_state'::text, NULL::uuid;
    RETURN;
  END IF;

  IF (
    SELECT count(*) FROM public.content_draft_events e
    WHERE e.actor_id = v_uid AND e.kind = 'comment' AND e.created_at > now() - interval '10 minutes'
  ) >= 30 THEN
    RETURN QUERY SELECT 'rate_limited'::text, NULL::uuid;
    RETURN;
  END IF;

  INSERT INTO public.content_draft_events (draft_id, version_id, actor_id, actor_role, kind, body)
  VALUES (p_draft_id, v_draft.current_version_id, v_uid, v_role, 'comment', v_body)
  RETURNING id INTO v_id;

  UPDATE public.content_drafts d SET updated_at = now() WHERE d.id = p_draft_id;

  IF v_role = 'creator' THEN
    SELECT COALESCE(NULLIF(btrim(u.username), ''), 'A creator') INTO v_name
    FROM public.users u WHERE u.id = v_uid;
    PERFORM public.content_draft_notify(
      v_contest.advertiser_id, v_draft.contest_id, 'content_draft_comment',
      'New message on a draft',
      v_name || ' wrote about a draft in ' || COALESCE(NULLIF(btrim(v_contest.title), ''), 'your campaign') || '.'
    );
  ELSE
    PERFORM public.content_draft_notify(
      v_draft.creator_id, v_draft.contest_id, 'content_draft_comment',
      'New message on your draft',
      public.content_draft_brand_name(v_draft.contest_id) || ' wrote about your draft for '
        || COALESCE(NULLIF(btrim(v_contest.title), ''), 'the campaign') || '.'
    );
  END IF;

  RETURN QUERY SELECT 'commented'::text, v_id;
END;
$$;

